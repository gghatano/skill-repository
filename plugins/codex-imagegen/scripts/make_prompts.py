"""prompts/ の依頼ファイルを生成する（Codex への画像生成入力）。

    python make_prompts.py        # or: uv run python make_prompts.py

各ファイルは画像 1 枚分。**図解**（インフォグラフィック）を PNG で作らせる入力になる。
テキストカードの羅列にしないため、レイアウトは指定せず「最重要メッセージ・想定読者・
希望する構造・強調事項」を渡し、内容は "素材" として与える。図解の実相（構図・装飾・色）は
Codex に委ねる。数字・日本語ラベルは一字も変えないこと。

このファイルが文言の**正本**。`prompts/*.md` は生成物なので手で編集しない
（次回このスクリプトを走らせると上書きされる）。文言を変えるときは下の `SLIDES` を直す。

--------------------------------------------------------------------------------
使い方の要点（テンプレートとして流用する人へ）
--------------------------------------------------------------------------------
1. AUDIENCE と HOUSE_STYLE を自分のプロジェクトに合わせて書き換える。
2. SLIDES を作りたい画像の分だけ並べる。各要素の意味は下のコメントを参照。
3. `python make_prompts.py` で prompts/ を作り直し、`./gen.sh` で生成する。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "prompts"
OUT.mkdir(exist_ok=True)

# ── ここから下はプロジェクトごとに書き換える ────────────────────────────────

# 想定読者。図中の文体・専門用語の扱いを決める土台になる。
AUDIENCE = "＜想定読者を書く。例: 経営層・社内（初見の非専門家）＞"

# 図の中のすべての文言に適用する文体ルール（＝ハウススタイル）。
# プロジェクト固有の言い換え・禁止語・敬体/常体の別はここに書く。配色は STYLE.md 側。
HOUSE_STYLE = """\
## 文体（図の中のすべての文言に適用）
＜読み手に合わせた文体ルールをここに書く。例:＞
- ＜です・ます体で統一する／常体で統一する など＞
- ＜煽り・口語・比喩を使わない など＞
- ＜専門用語・略語をそのまま出さない。素材にある平易な言い換えを使う。図に出さない語の例を列挙＞
- **素材の語句と数値をそのまま使う。** 言い回しを自分で崩したり、余計な文言を足したりしない。"""

# stem, label(キッカー), headline(主タイトル＝完全な文), key(最重要の 1 点),
# structure(希望する構造), emphasis(視覚的に強調したいこと),
# blocks(素材: [(見出し, [要点...]), ...]), facts(必ず正確に載せる数値 [...]), note(個別メモ)
SLIDES = [
    ("01-overview", "＜キッカー＞",
     "＜この 1 枚の結論を、完全な文のヘッドラインで。最も大きく見せる＞",
     "＜この 1 枚で理解してほしい 1 つ＞",
     "＜希望する構造。例: 比較と集約 — 2 つの値を対等に並べ 1 つの結果へ合流させる図＞",
     "＜視覚的に特に強調したいこと。例: 採用された値だけを 1 色で囲む＞",
     [("＜素材の見出し 1＞", ["＜要点＞", "＜要点＞", "＜要点＞"]),
      ("＜素材の見出し 2＞", ["＜要点＞", "＜要点＞"]),
      ("＜素材の見出し 3＞", ["＜要点＞", "＜要点＞", "＜要点＞"])],
     ["＜必ず正確に載せる数値＞"],
     "＜このスライド固有のメモがあれば。無ければ空文字＞"),

    ("02-detail", "＜キッカー＞",
     "＜ヘッドライン＞",
     "＜最重要の 1 点＞",
     "＜希望する構造＞",
     "＜強調したいこと＞",
     [("＜見出し＞", ["＜要点＞", "＜要点＞"]),
      ("＜見出し＞", ["＜要点＞", "＜要点＞", "＜要点＞"])],
     [],
     ""),
]

# ── ここから下はテンプレート本体。通常は触らない ──────────────────────────

TEMPLATE = """\
「画像生成ルール」（AGENTS.md）に従い、下を **1 枚の図解** に整理する。
**文章をカードに並べるだけにしない。** アイコン・配置・矢印で、見れば構造が分かる図にする。
数字・日本語ラベルは一字も変えない。

{house_style}

## 組版（STYLE.md の下限を必ず満たす）
- **文字は大きく。** STYLE.md の文字サイズ下限を満たす（1920px 幅での実寸）。
  **入らないときは要素を減らす。縮めない。**
- **日本語を助詞や 1 文字で折らない。** 文節ごとに `display:inline-block` で包むか `<br>` を自分で置く。
- **絵文字・装飾記号・アイコンフォントを使わない**（`□` が出る）。図形は SVG か罫線で描く。
- **同じ文言を 2 箇所に出さない。**「最重要メッセージ」を図の中にそのまま貼らない。
- **線は 1 関係 1 本。** 端点はカードの縁に接続する。宙に浮いた線・二重の矢印を作らない。
  並列の列挙に矢印を使わない。

## ラベル（上に小さく添えるキッカー）
{label}

## ヘッドライン（完全な文のメッセージ＝主タイトル。最も大きく）
{headline}

## 最重要メッセージ（この 1 枚で理解してほしい 1 つ）
{key}

## 想定読者
{audience}

## 希望する構造
{structure}

## 特に強調したいこと（視覚的に）
{emphasis}

## 素材（図に落とす中身。※そのまま箇条書きで並べない。構造に符号化する）
{blocks}
{facts}## 出力
- infographic PNG: `out/{stem}.png`（フルスライド 16:9・幅 1920px・ライト地）。
- 見れば構造が伝わる図に。テキストは要点のキーワードと数値だけを図の部品に埋める。
{note}"""


def render_blocks(blocks):
    out = []
    for label, pts in blocks:
        out.append(f"### {label}")
        out.extend(f"- {p}" for p in pts)
        out.append("")
    return "\n".join(out)


def main() -> None:
    for stem, label, headline, key, structure, emphasis, blocks, facts, note in SLIDES:
        f_txt = ""
        if facts:
            f_txt = "## 必ず正確に載せる数値（変えない）\n" + "、".join(facts) + "\n\n"
        body = TEMPLATE.format(
            stem=stem, label=label, headline=headline, key=key, audience=AUDIENCE,
            house_style=HOUSE_STYLE, structure=structure, emphasis=emphasis,
            blocks=render_blocks(blocks), facts=f_txt,
            note=(f"- {note}\n" if note else ""))
        (OUT / f"{stem}.md").write_text(body, encoding="utf-8")
    print(f"{len(SLIDES)} 個の依頼ファイルを {OUT} に書き出しました。")


if __name__ == "__main__":
    main()
